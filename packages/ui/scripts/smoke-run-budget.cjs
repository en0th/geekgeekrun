const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const assert = require('node:assert/strict'), { createRequire } = require('node:module'), { EventEmitter } = require('node:events')
if (!process.env.GGR_QA_ARCHIVE || !path.isAbsolute(process.env.GGR_QA_ARCHIVE))
  throw Error('请用 GGR_QA_ARCHIVE 指定待验收 app.asar 的绝对路径，并用打包后的 Electron 执行此脚本')
const fromApp = createRequire(process.env.GGR_QA_ARCHIVE + '/package.json')
const fromLauncher = createRequire(fromApp.resolve('@geekgeekrun/launch-bosszhipin-login-page-with-preload-extension/package.json'))
const coreFile = fromLauncher.resolve('@geekgeekrun/geek-auto-start-chat-with-boss/run-budget.mjs')
const fromCore = createRequire(coreFile)
const { createRunBudget } = fromCore(coreFile)
const { createBudgetStore } = fromCore('./run-budget-store.mjs')
const { attachJobRequestBudget } = fromCore('./job-request-budget.mjs')
const { CDPSessionEvent } = fromCore('puppeteer')
const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'ggr-packaged-budget-'))
;(async () => {
  try {
    const store = createBudgetStore(folder, 42), calls = []
    const budget = createRunBudget({ limits: { requests:2, detailRequests:2, activeMinutes:1 }, persist: store.save })
    const session = new EventEmitter()
    session.send = async (method, args) => {
      if (method === 'Fetch.continueRequest') assert.ok(store.load().usage.requests >= 1)
      calls.push({ method, args })
    }
    budget.resume()
    const monitor = await attachJobRequestBudget({ createCDPSession: async () => session }, budget)
    for (let i=0;i<3;i++) session.emit('Fetch.requestPaused', { requestId:String(i), request:{url:'https://www.zhipin.com/wapi/zpgeek/search/joblist.json?query=fixture'} })
    await new Promise(resolve=>setImmediate(resolve))
    assert.equal(calls.filter(c=>c.method==='Fetch.continueRequest').length,2)
    assert.equal(calls.filter(c=>c.method==='Fetch.failRequest').length,1)
    assert.equal(store.load().usage.requests,2)
    await assert.rejects(budget.guard(()=>1),/RUN_BUDGET_EXCEEDED/)
    monitor.dispose()
    const resumed = createRunBudget({ limits:{requests:3,detailRequests:2,activeMinutes:1}, saved:store.load(),persist:store.save })
    resumed.resume(); resumed.reserveRequest('detail'); resumed.pause()
    assert.equal(store.load().usage.requests,3)
    assert.equal(store.load().usage.detailRequests,1)
    assert.equal(CDPSessionEvent.Disconnected,fromCore('puppeteer-extra').pptr.CDPSessionEvent.Disconnected)
    console.log('PACKAGED_BUDGET_MODULES_OK: persisted before release; denied N+1; resumed usage preserved; CJS CDP Symbol matches.')
  } finally { fs.rmSync(folder,{recursive:true,force:true}) }
})().catch(error=>{console.error(error);process.exitCode=1})
